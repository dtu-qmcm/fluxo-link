#!/usr/bin/env python3
"""Generate docs/core_profile.md: the `core` subset of the schema on one page.

The core profile is the minimal record most datasets should fill and a
database should index. It is generated from the `in_subset: [core]` marks in
src/fluxolink/schema/*.yaml, so it cannot drift from the schema; re-run after
any schema change (`just core-profile`).

Usage:  python scripts/gen_core_profile.py [--check]
"""

from __future__ import annotations

import argparse
import glob
import sys
from pathlib import Path
from typing import Any

import yaml

REPO = Path(__file__).resolve().parent.parent
SCHEMA_DIR = REPO / "src" / "fluxolink" / "schema"
OUT = REPO / "docs" / "core_profile.md"
EXAMPLE = REPO / "examples" / "valid" / "minimal_core_record.yaml"

# Reading order: study and cultivation, tracer design, run, results.
ORDER = [
    "FluxoDataset",
    "Investigation",
    "Condition",
    "LabelingExperiment",
    "LabeledSource",
    "TracerIsotopomer",
    "SimulationRun",
    "SoftwareInfo",
    "FluxSolution",
    "FluxResult",
    "GoodnessOfFit",
    "SourceFile",
]


def _classes() -> dict[str, dict[str, Any]]:
    classes: dict[str, dict[str, Any]] = {}
    for path in sorted(glob.glob(str(SCHEMA_DIR / "*.yaml"))):
        if Path(path).name == "flux_record.yaml":  # a derived view, not the dataset
            continue
        doc = yaml.safe_load(Path(path).read_text(encoding="utf-8"))
        classes.update(doc.get("classes") or {})
    return classes


def _first_sentence(text: str | None) -> str:
    text = " ".join((text or "").split())
    end = text.find(". ")
    sentence = text if end < 0 else text[: end + 1]
    return sentence.replace("|", "\\|")


def _range(slot: dict[str, Any]) -> str:
    rng = slot.get("range", "string")
    return f"{rng} (list)" if slot.get("multivalued") else rng


def render() -> str:
    """Render the core profile page.

    Returns:
        The Markdown text.
    """
    classes = _classes()
    total = sum(len(c.get("attributes") or {}) for c in classes.values())
    lines = [
        "# Core profile",
        "",
        "<!-- Generated by scripts/gen_core_profile.py from the `core` subset of the",
        "     schema. Do not edit by hand; run `just core-profile`. -->",
        "",
        "The `core` subset is the minimal record: what most datasets should fill and",
        "what a database should index. It covers the study and its cultivation, the",
        "tracer design, the method and software of each run, the flux results with",
        "their uncertainty, and the native source files.",
        "",
        "Everything else in the schema is optional detail. Benchmarks need some of it",
        "(networks, atom transitions, measurements; see VALIDATION_REQUIREMENTS.md),",
        "and tool provenance uses the rest (solver options, residuals, scale factors).",
        "`fluxo ingest` fills most fields from the native files, so nobody types them",
        "by hand.",
        "",
    ]
    rows = []
    for name in ORDER:
        attrs = (classes.get(name) or {}).get("attributes") or {}
        core = {
            slot: spec or {}
            for slot, spec in attrs.items()
            if "core" in ((spec or {}).get("in_subset") or [])
        }
        if not core:
            continue
        rows.append((name, core))
    n_core = sum(len(core) for _, core in rows)
    lines += [
        f"**{n_core} core fields in {len(rows)} classes**, out of {total} fields in",
        f"{len(classes)} classes. Required fields are marked; the rest are recommended.",
        "",
    ]
    for name, core in rows:
        lines += [f"## {name}", "", "| Field | Type | Required | Meaning |", "|---|---|---|---|"]
        for slot, spec in core.items():
            required = "yes" if spec.get("required") or spec.get("identifier") else ""
            lines.append(
                f"| `{slot}` | {_range(spec)} | {required} | "
                f"{_first_sentence(spec.get('description'))} |"
            )
        lines.append("")
    lines += [
        "## Example",
        "",
        # as_posix: the page must be identical on Windows, where str(Path) uses "\".
        f"A complete core record (`{EXAMPLE.relative_to(REPO).as_posix()}`, illustrative values):",
        "",
        "```yaml",
        EXAMPLE.read_text(encoding="utf-8").rstrip(),
        "```",
        "",
    ]
    return "\n".join(lines)


def main(argv: list[str]) -> int:
    """Write (or with --check, verify) docs/core_profile.md."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if the page is stale")
    args = parser.parse_args(argv)
    text = render()
    if args.check:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print(f"{OUT} is out of date; run scripts/gen_core_profile.py", file=sys.stderr)
            return 1
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
